-- Data API access must be explicitly granted; all test objects are synthetic.
BEGIN;

CREATE EXTENSION IF NOT EXISTS pgtap WITH SCHEMA extensions;
SET LOCAL search_path = public, extensions;

CREATE TABLE public.api_default_acl_probe (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE FUNCTION public.api_default_acl_probe_fn()
RETURNS INTEGER
LANGUAGE SQL
AS $$ SELECT 1 $$;

SELECT plan(38);

-- Existing trigger functions must not be callable as anon, authenticated, or
-- service_role RPCs. Their database triggers remain attached to their tables.
SELECT ok(NOT has_function_privilege('anon', 'public.erp4_ppdb_update_updated_at_column()', 'EXECUTE'), 'anon cannot call the PPDB timestamp trigger');
SELECT ok(NOT has_function_privilege('authenticated', 'public.erp4_ppdb_update_updated_at_column()', 'EXECUTE'), 'authenticated cannot call the PPDB timestamp trigger');
SELECT ok(NOT has_function_privilege('service_role', 'public.erp4_ppdb_update_updated_at_column()', 'EXECUTE'), 'service_role cannot call the PPDB timestamp trigger directly');
SELECT ok(NOT has_function_privilege('anon', 'public.set_updated_at()', 'EXECUTE'), 'anon cannot call the shared timestamp trigger');
SELECT ok(NOT has_function_privilege('authenticated', 'public.set_updated_at()', 'EXECUTE'), 'authenticated cannot call the shared timestamp trigger');
SELECT ok(NOT has_function_privilege('service_role', 'public.set_updated_at()', 'EXECUTE'), 'service_role cannot call the shared timestamp trigger directly');
SELECT ok(NOT has_function_privilege('anon', 'public.sync_user_profile_to_tenant_profile()', 'EXECUTE'), 'anon cannot call the SECURITY DEFINER profile trigger');
SELECT ok(NOT has_function_privilege('authenticated', 'public.sync_user_profile_to_tenant_profile()', 'EXECUTE'), 'authenticated cannot call the SECURITY DEFINER profile trigger');
SELECT ok(NOT has_function_privilege('service_role', 'public.sync_user_profile_to_tenant_profile()', 'EXECUTE'), 'service_role cannot call the SECURITY DEFINER profile trigger directly');
SELECT ok(NOT has_function_privilege('anon', 'public.validate_master_data_record()', 'EXECUTE'), 'anon cannot call the master-data validation trigger');
SELECT ok(NOT has_function_privilege('authenticated', 'public.validate_master_data_record()', 'EXECUTE'), 'authenticated cannot call the master-data validation trigger');
SELECT ok(NOT has_function_privilege('service_role', 'public.validate_master_data_record()', 'EXECUTE'), 'service_role cannot call the master-data validation trigger directly');
SELECT is(
  (SELECT count(*)::INTEGER FROM information_schema.routine_privileges
   WHERE specific_schema = 'public' AND grantee = 'anon' AND privilege_type = 'EXECUTE'),
  0,
  'anon has no EXECUTE grant on public functions'
);

-- Creating a table after the hardening migration must not expose it to any
-- Data API role. Existing table grants are intentionally outside this test.
SELECT ok(NOT has_table_privilege('anon', 'public.api_default_acl_probe', 'SELECT'), 'new public table is not readable by anon');
SELECT ok(NOT has_table_privilege('anon', 'public.api_default_acl_probe', 'INSERT'), 'new public table is not writable by anon');
SELECT ok(NOT has_table_privilege('anon', 'public.api_default_acl_probe', 'UPDATE'), 'new public table is not updatable by anon');
SELECT ok(NOT has_table_privilege('anon', 'public.api_default_acl_probe', 'DELETE'), 'new public table is not deletable by anon');
SELECT ok(NOT has_table_privilege('authenticated', 'public.api_default_acl_probe', 'SELECT'), 'new public table is not readable by authenticated');
SELECT ok(NOT has_table_privilege('authenticated', 'public.api_default_acl_probe', 'INSERT'), 'new public table is not writable by authenticated');
SELECT ok(NOT has_table_privilege('authenticated', 'public.api_default_acl_probe', 'UPDATE'), 'new public table is not updatable by authenticated');
SELECT ok(NOT has_table_privilege('authenticated', 'public.api_default_acl_probe', 'DELETE'), 'new public table is not deletable by authenticated');
SELECT ok(NOT has_table_privilege('service_role', 'public.api_default_acl_probe', 'SELECT'), 'new public table is not readable by service_role without an explicit grant');
SELECT ok(NOT has_table_privilege('service_role', 'public.api_default_acl_probe', 'INSERT'), 'new public table is not writable by service_role without an explicit grant');
SELECT ok(NOT has_table_privilege('service_role', 'public.api_default_acl_probe', 'UPDATE'), 'new public table is not updatable by service_role without an explicit grant');
SELECT ok(NOT has_table_privilege('service_role', 'public.api_default_acl_probe', 'DELETE'), 'new public table is not deletable by service_role without an explicit grant');

-- New public sequences also require explicit grants.
SELECT ok(NOT has_sequence_privilege('anon', pg_get_serial_sequence('public.api_default_acl_probe', 'id'), 'USAGE'), 'new public sequence is not usable by anon');
SELECT ok(NOT has_sequence_privilege('anon', pg_get_serial_sequence('public.api_default_acl_probe', 'id'), 'SELECT'), 'new public sequence is not readable by anon');
SELECT ok(NOT has_sequence_privilege('anon', pg_get_serial_sequence('public.api_default_acl_probe', 'id'), 'UPDATE'), 'new public sequence is not updatable by anon');
SELECT ok(NOT has_sequence_privilege('authenticated', pg_get_serial_sequence('public.api_default_acl_probe', 'id'), 'USAGE'), 'new public sequence is not usable by authenticated');
SELECT ok(NOT has_sequence_privilege('authenticated', pg_get_serial_sequence('public.api_default_acl_probe', 'id'), 'SELECT'), 'new public sequence is not readable by authenticated');
SELECT ok(NOT has_sequence_privilege('authenticated', pg_get_serial_sequence('public.api_default_acl_probe', 'id'), 'UPDATE'), 'new public sequence is not updatable by authenticated');
SELECT ok(NOT has_sequence_privilege('service_role', pg_get_serial_sequence('public.api_default_acl_probe', 'id'), 'USAGE'), 'new public sequence is not usable by service_role without an explicit grant');
SELECT ok(NOT has_sequence_privilege('service_role', pg_get_serial_sequence('public.api_default_acl_probe', 'id'), 'SELECT'), 'new public sequence is not readable by service_role without an explicit grant');
SELECT ok(NOT has_sequence_privilege('service_role', pg_get_serial_sequence('public.api_default_acl_probe', 'id'), 'UPDATE'), 'new public sequence is not updatable by service_role without an explicit grant');

-- New functions must not inherit PostgreSQL's default PUBLIC EXECUTE grant.
SELECT ok(NOT has_function_privilege('anon', 'public.api_default_acl_probe_fn()', 'EXECUTE'), 'new public function is not callable by anon');
SELECT ok(NOT has_function_privilege('authenticated', 'public.api_default_acl_probe_fn()', 'EXECUTE'), 'new public function is not callable by authenticated');
SELECT ok(NOT has_function_privilege('service_role', 'public.api_default_acl_probe_fn()', 'EXECUTE'), 'new public function requires an explicit service_role grant');

SELECT is(
  (SELECT proconfig FROM pg_proc WHERE oid = 'public.erp4_ppdb_update_updated_at_column()'::regprocedure),
  ARRAY['search_path=pg_catalog']::TEXT[],
  'legacy PPDB timestamp trigger pins search_path to pg_catalog'
);
SELECT * FROM finish();
ROLLBACK;

